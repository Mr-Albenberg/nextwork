"""Train a small, original EvidenceNet classifier on CPU and export browser weights."""
import json
from pathlib import Path
import numpy as np
from sklearn.neural_network import MLPClassifier
from sklearn.metrics import accuracy_score, f1_score, confusion_matrix

ROOT = Path(__file__).resolve().parent
rows = json.loads((ROOT/'data/features.json').read_text())
manifest = json.loads((ROOT/'data/manifest.json').read_text())
train = [r for r in rows if r['split'] == 'train']
model = MLPClassifier(hidden_layer_sizes=(16,), activation='tanh', solver='lbfgs', alpha=0.15,
                      max_iter=2000, random_state=1749, tol=1e-8)
model.fit(np.array([r['x'] for r in train]), np.array([r['label'] for r in train]))
metrics = {}
for split in ['train', 'validation', 'test']:
    selected = [r for r in rows if r['split'] == split]
    x, y = np.array([r['x'] for r in selected]), [r['label'] for r in selected]
    pred = model.predict(x)
    metrics[split] = {'count':len(y), 'accuracy':round(accuracy_score(y,pred),4),
                      'macroF1':round(f1_score(y,pred,average='macro'),4),
                      'confusion':confusion_matrix(y,pred,labels=model.classes_).tolist()}
artifact = {'id':'nextwork-evidencenet-v1', 'name':'Nextwork Match · EvidenceNet v1', 'version':'1.0.0-beta.1',
            'architecture':'16 input features → 16 tanh units → 4 softmax classes',
            'training':'Original supervised MLP, trained from scratch on authored synthetic evidence pairs',
            'seed':1749, 'dataSha256':manifest['sha256'], 'featuresSha256':manifest['featuresSha256'], 'featureNames':manifest['featureNames'],
            'classes':model.classes_.tolist(),
            'weights':[np.round(w,9).tolist() for w in model.coefs_],
            'biases':[np.round(b,9).tolist() for b in model.intercepts_],
            'metrics':metrics, 'limitations':'Synthetic bootstrap model. Metrics are synthetic-only, not real-world accuracy, hiring likelihood, or verified proficiency.'}
verification = []
for split in ['train', 'validation', 'test']:
    chosen = [r for r in rows if r['split'] == split]
    for row in chosen[::max(1, len(chosen)//12)][:12]:
        proba = model.predict_proba(np.array([row['x']]))[0]
        verification.append({'id':row['id'], 'x':row['x'], 'probabilities':proba.tolist(), 'label':str(model.predict([row['x']])[0])})
(ROOT/'verification.json').write_text(json.dumps(verification,indent=2)+'\n')
encoded = json.dumps(artifact,separators=(',',':'))
output = ROOT.parent.parent/'dist/nextwork-model.js'
output.write_text('// Generated by models/nextwork-match/train.py. Do not hand-edit learned weights.\n'
                  '(function(root){const model='+encoded+';if(typeof module!=="undefined")module.exports=model;'
                  'else root.NextworkModel=model;})(typeof window!=="undefined"?window:globalThis);\n')
(ROOT/'evaluation.json').write_text(json.dumps({'dataset':manifest['sha256'],'classes':model.classes_.tolist(),'syntheticOnly':True,'metrics':metrics},indent=2)+'\n')
print(json.dumps(metrics,indent=2))
print(f'Exported {output.stat().st_size} bytes to {output}')
